#!/usr/bin/env bun
/**
 * Write `apps/api/src/water-program/plan-sections.generated.ts` from the plan
 * definitions in ../plans.ts, so the plan writer in the API knows each plan's section
 * order and "what to record" prompts without duplicating them by hand:
 *
 *   bun packages/db/prisma/seed/sources/water/extract/generate-plan-sections.ts
 */
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { PLAN_FIELDS } from '../plan-fields';
import { PLANS } from '../plans';

const OUTPUT = join(__dirname, '../../../../../../../apps/api/src/water-program/plan-sections.generated.ts');

const sections = Object.fromEntries(
  PLANS.map((p) => [
    p.key,
    {
      name: p.name,
      sections: p.sections.map((s) => {
        const fields = PLAN_FIELDS[p.key]?.[s.title];
        if (!fields?.length) throw new Error(`${p.key}: no fill-in fields for section "${s.title}"`);
        return { title: s.title, prompts: s.prompts, fields };
      }),
    },
  ]),
);

writeFileSync(
  OUTPUT,
  `// ============================================================================
// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
// Generated by: bun packages/db/prisma/seed/sources/water/extract/generate-plan-sections.ts
// Source: packages/db/prisma/seed/sources/water/plans.ts
// ============================================================================

export type WaterPlanKey = 'crmp' | 'cirp';

export type PlanAutoKey = 'epa_assessment' | 'risk_register' | 'last_exercise' | 'next_exercise';

export interface PlanFieldDef {
  label: string;
  hint?: string;
  long?: boolean;
  /** Filled in by the platform from its own records. */
  auto?: PlanAutoKey;
  /** Not counted in the plan's completeness. */
  optional?: boolean;
}

export interface PlanSectionDef {
  title: string;
  prompts: string[];
  fields: PlanFieldDef[];
}

export const PLAN_SECTIONS: Record<WaterPlanKey, { name: string; sections: PlanSectionDef[] }> = ${JSON.stringify(sections, null, 2)};
`,
);
console.log(`wrote ${OUTPUT}: ${PLANS.map((p) => `${p.key} ${p.sections.length} sections`).join(', ')}`);
