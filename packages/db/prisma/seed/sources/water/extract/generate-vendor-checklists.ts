#!/usr/bin/env bun
/**
 * Write `apps/api/src/vendor-checklists/checklists.generated.ts` from the EPA procurement
 * checklist JSON extracted next door (inputs/epa-procurement-checklist.json, EPA
 * Cybersecurity Procurement Evaluation Checklist, public domain):
 *
 *   bun packages/db/prisma/seed/sources/water/extract/generate-vendor-checklists.ts
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const INPUT = join(__dirname, '../inputs/epa-procurement-checklist.json');
const OUTPUT = join(__dirname, '../../../../../../apps/api/src/vendor-checklists/checklists.generated.ts');

interface Item {
  id: string;
  section: string;
  question: string;
  exampleResponse: string;
  recommendation: string;
  referenceUrl: string;
}
interface Input {
  source: string;
  weightScale: Record<string, string>;
  scoreScale: Record<string, string>;
  checklists: Array<{ kind: string; name: string; items: Item[] }>;
}

const input = JSON.parse(readFileSync(INPUT, 'utf8')) as Input;
const checklists = input.checklists.map((c) => ({
  kind: c.kind,
  name: c.name,
  source: input.source,
  sections: [...new Set(c.items.map((i) => i.section))],
  items: c.items,
}));

const out = `// ============================================================================
// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY
// Generated by: bun packages/db/prisma/seed/sources/water/extract/generate-vendor-checklists.ts
// Source: packages/db/prisma/seed/sources/water/inputs/epa-procurement-checklist.json
// ============================================================================

export type VendorChecklistKind = 'epa_supplier' | 'epa_integrator_msp';

export interface VendorChecklistItemDef {
  id: string;
  section: string;
  question: string;
  exampleResponse: string;
  recommendation: string;
  referenceUrl: string;
}

export interface VendorChecklistDef {
  kind: VendorChecklistKind;
  name: string;
  source: string;
  sections: string[];
  items: VendorChecklistItemDef[];
}

/** EPA's weight scale (priority of the item to the utility). */
export const WEIGHT_SCALE: Record<number, string> = ${JSON.stringify(
  Object.fromEntries(Object.entries(input.weightScale).map(([k, v]) => [Number(k), v])),
  null,
  2,
)};

/** EPA's score ranking (how well the supplier's response meets the item). */
export const SCORE_SCALE: Record<number, string> = ${JSON.stringify(
  Object.fromEntries(Object.entries(input.scoreScale).map(([k, v]) => [Number(k), v])),
  null,
  2,
)};

export const VENDOR_CHECKLISTS: Record<VendorChecklistKind, VendorChecklistDef> = ${JSON.stringify(
  Object.fromEntries(checklists.map((c) => [c.kind, c])),
  null,
  2,
)} as const;
`;
writeFileSync(OUTPUT, out);
console.log(`wrote ${OUTPUT}: ${checklists.map((c) => `${c.kind} ${c.items.length} items`).join(', ')}`);
