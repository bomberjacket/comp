/**
 * Generate `src/manifests/scubagear/policies.generated.ts`: the SCuBA policy
 * catalogue (id, product, group, requirement, criticality, automated) joined
 * with CISA's SCuBA -> NIST SP 800-53 r5 mapping.
 *
 * Inputs are files from the cisagov/ScubaGear repository (not committed here):
 *   - a full ScubaResults_<uuid>.json produced by that ScubaGear version
 *     (PowerShell/ScubaGear/Sample-Reports has one), which lists every policy
 *     of every product with its requirement text and criticality;
 *   - PowerShell/ScubaGear/mappings/scuba-to-nist-sp-800-53-r5-fedramp-high.csv.
 *
 * Run with:
 *   bun run scripts/generate-scubagear-policies.ts --results <file> --mapping <csv> --version 2.0.0
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';
import { compactScubaResults, policyBaseId } from '../src/manifests/scubagear/results';
import type { ScubaPolicyDef, ScubaProduct } from '../src/manifests/scubagear/types';
import { SCUBA_PRODUCTS } from '../src/manifests/scubagear/types';
import type { ScubaRawResults } from '../src/manifests/scubagear/types';

const OUTPUT = join(__dirname, '../src/manifests/scubagear/policies.generated.ts');

function arg(name: string): string {
  const i = process.argv.indexOf(`--${name}`);
  if (i < 0 || !process.argv[i + 1]) throw new Error(`Missing --${name}`);
  return process.argv[i + 1];
}

/** `MS.AAD.1.1v1,"AC-2(12), AC-2(13)"` rows; a policy may appear more than once. */
function readMapping(path: string): Map<string, string[]> {
  const map = new Map<string, string[]>();
  for (const line of readFileSync(path, 'utf-8').replace(/^﻿/, '').split(/\r?\n/)) {
    const m = line.match(/^(MS\.[A-Z]+\.\d+\.\d+v\d+),"?([^"]*)"?\s*$/);
    if (!m) continue;
    const controls = m[2]
      .split(',')
      .map((c) => c.trim())
      .filter(Boolean);
    const existing = map.get(m[1]) ?? [];
    map.set(m[1], [...new Set([...existing, ...controls])]);
  }
  if (map.size === 0) throw new Error('No mapping rows found');
  return map;
}

function controlsFor(mapping: Map<string, string[]>, id: string): string[] {
  if (mapping.has(id)) return mapping.get(id)!;
  const base = policyBaseId(id);
  for (const [key, value] of mapping) if (policyBaseId(key) === base) return value;
  return [];
}

const sq = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function main(): void {
  const resultsPath = arg('results');
  const version = arg('version');
  const mapping = readMapping(arg('mapping'));
  const raw = JSON.parse(readFileSync(resultsPath, 'utf-8').replace(/^﻿/, '')) as ScubaRawResults;
  const compact = compactScubaResults(raw);

  const references = new Map<string, string>();
  for (const groups of Object.values(raw.Results)) {
    for (const g of groups) references.set(`${g.GroupNumber}|${g.GroupName}`, g.GroupReferenceURL ?? '');
  }

  const defs: ScubaPolicyDef[] = [];
  let unmapped = 0;
  for (const p of compact.policies) {
    if (!(p.product in SCUBA_PRODUCTS)) throw new Error(`Unknown product ${p.product}`);
    const nist80053 = controlsFor(mapping, p.id);
    if (nist80053.length === 0) unmapped++;
    defs.push({
      id: p.id,
      base: policyBaseId(p.id),
      product: p.product as ScubaProduct,
      groupNumber: p.groupNumber,
      groupName: p.groupName,
      reference: references.get(`${p.groupNumber}|${p.groupName}`) ?? '',
      requirement: p.requirement,
      criticality: p.criticality,
      automated: !p.manual,
      bod2501: p.bod2501,
      nist80053,
    });
  }
  const ids = new Set(defs.map((d) => d.id));
  if (ids.size !== defs.length) throw new Error('Duplicate policy ids in results');

  const lines: string[] = [
    '// ============================================================================',
    '// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY',
    '// Generated by: bun run scripts/generate-scubagear-policies.ts',
    `// Source: CISA ScubaGear ${version} baselines (Sample-Reports results) and`,
    '//         mappings/scuba-to-nist-sp-800-53-r5-fedramp-high.csv',
    '// ============================================================================',
    '',
    "import type { ScubaPolicyDef } from './types';",
    '',
    `export const SCUBA_BASELINE_VERSION = ${sq(version)};`,
    '',
    '/** Every SCuBA policy in the baselines, in report order. */',
    'export const SCUBA_POLICIES: ScubaPolicyDef[] = [',
  ];
  for (const d of defs) {
    lines.push('  {');
    lines.push(`    id: ${sq(d.id)},`);
    lines.push(`    base: ${sq(d.base)},`);
    lines.push(`    product: ${sq(d.product)},`);
    lines.push(`    groupNumber: ${sq(d.groupNumber)},`);
    lines.push(`    groupName: ${sq(d.groupName)},`);
    lines.push(`    reference: ${sq(d.reference)},`);
    lines.push(`    requirement: ${sq(d.requirement)},`);
    lines.push(`    criticality: ${sq(d.criticality)},`);
    lines.push(`    automated: ${d.automated},`);
    lines.push(`    bod2501: ${d.bod2501},`);
    lines.push(`    nist80053: [${d.nist80053.map(sq).join(', ')}],`);
    lines.push('  },');
  }
  lines.push('];', '');
  writeFileSync(OUTPUT, lines.join('\n'));
  console.log(`Wrote ${defs.length} policies (${unmapped} without an 800-53 mapping) to ${OUTPUT}`);
}

main();
