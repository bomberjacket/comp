/**
 * Generate `src/task-mappings.nist-800-171.ts` from the NIST SP 800-171 task templates
 * emitted by the seed generator (one task per assessment objective). Keys are the NIST
 * objective identifiers, so a check maps to one objective:
 *
 *   taskMapping: TASK_TEMPLATES['3.5.3[a]']
 *
 * Run with: bun run scripts/generate-nist-task-mappings.ts
 */
import { readFileSync, writeFileSync } from 'fs';
import { join } from 'path';

interface TaskTemplate {
  id: string;
  name: string;
  description: string;
  frequency: string;
  department: string;
}

const INPUT = join(
  __dirname,
  '../../../packages/db/prisma/seed/primitives/FrameworkEditorTaskTemplate.nist-800-171.json',
);
const OUTPUT = join(__dirname, '../src/task-mappings.nist-800-171.ts');

/** `3.1.1[a] Authorized users are identified` -> `3.1.1[a]` */
function objectiveId(name: string): string {
  const id = name.split(' ')[0] ?? '';
  if (!/^(\d+\.\d+\.\d+\[[a-z]\]|A\.\d\d\.\d\d\.\d\d\S*)$/.test(id)) {
    throw new Error(`Task name does not start with a NIST objective id: ${name}`);
  }
  return id;
}

const sq = (value: string) => `'${value.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`;

function main(): void {
  const tasks: TaskTemplate[] = JSON.parse(readFileSync(INPUT, 'utf-8'));
  const sorted = [...tasks].sort((a, b) => a.name.localeCompare(b.name, 'en', { numeric: true }));
  const keys = new Set<string>();
  const lines: string[] = [
    '// ============================================================================',
    '// AUTO-GENERATED FILE - DO NOT EDIT DIRECTLY',
    '// Generated by: bun run scripts/generate-nist-task-mappings.ts',
    '// Source: packages/db/prisma/seed/primitives/FrameworkEditorTaskTemplate.nist-800-171.json',
    '// ============================================================================',
    '',
    '/** NIST SP 800-171 evidence task template ids, one per assessment objective. */',
    'export const NIST_800_171_TASK_TEMPLATE_IDS = [',
  ];
  for (const t of sorted) lines.push(`  ${sq(t.id)}, // ${t.name.replace(/\*\//g, '*\\/')}`);
  lines.push('] as const;', '');
  lines.push(
    '/** Objective identifier (e.g. `3.5.3[a]`, `A.03.05.03[01]`) -> task template id. */',
  );
  lines.push('export const NIST_800_171_TASK_TEMPLATES = {');
  for (const t of sorted) {
    const key = objectiveId(t.name);
    if (keys.has(key)) throw new Error(`Duplicate objective id ${key}`);
    keys.add(key);
    lines.push(`  ${sq(key)}: ${sq(t.id)},`);
  }
  lines.push('} as const;', '');
  lines.push('/** Task template metadata for reference. */');
  lines.push('export const NIST_800_171_TASK_TEMPLATE_INFO: Record<');
  lines.push('  (typeof NIST_800_171_TASK_TEMPLATE_IDS)[number],');
  lines.push('  { name: string; description: string; department: string; frequency: string }');
  lines.push('> = {');
  for (const t of sorted) {
    const desc = t.description.replace(/\s+/g, ' ').substring(0, 100);
    lines.push(`  ${sq(t.id)}: {`);
    lines.push(`    name: ${sq(t.name)},`);
    lines.push(`    description: ${sq(`${desc}...`)},`);
    lines.push(`    department: ${sq(t.department)},`);
    lines.push(`    frequency: ${sq(t.frequency)},`);
    lines.push('  },');
  }
  lines.push('};', '');
  writeFileSync(OUTPUT, lines.join('\n'));
  console.log(`Generated ${OUTPUT}: ${sorted.length} NIST task templates`);
}

main();
